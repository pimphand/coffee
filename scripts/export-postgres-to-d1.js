// ── One-off: pindahkan data dari Postgres LAMA (mis. Supabase) ke Cloudflare D1 ──
//
// Script ini TIDAK dipakai aplikasi saat runtime — hanya untuk export data lama.
//
//   1. isi SOURCE_DATABASE_URL di .env (koneksi Postgres lama kamu)
//   2. node scripts/export-postgres-to-d1.js
//      → menghasilkan db/export/d1-import.sql
//   3. import ke D1:
//      npx wrangler d1 execute DB --file db/export/d1-import.sql --local   # D1 lokal
//      npx wrangler d1 execute DB --file db/export/d1-import.sql --remote  # D1 produksi
//
// Konversi PostgreSQL → SQLite yang dilakukan:
//   * timestamptz → unix epoch (integer)
//   * boolean     → 1 / 0
//   * text[]      → string JSON
//
// Setelah data lama berhasil dipindah, dependency `postgres` boleh dihapus
// dari devDependencies: bun remove postgres
import postgres from 'postgres';
import dotenv from 'dotenv';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

dotenv.config();

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'db', 'export', 'd1-import.sql');

const url = process.env.SOURCE_DATABASE_URL;
if (!url) {
  console.error('❌ SOURCE_DATABASE_URL is required (Postgres lama, mis. Supabase)');
  process.exit(1);
}

// ── helpers ───────────────────────────────────────────────────────
const q = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'boolean') return v ? '1' : '0';
  if (typeof v === 'number') return String(v);
  if (v instanceof Date) return String(Math.floor(v.getTime() / 1000));
  if (Array.isArray(v)) return `'${JSON.stringify(v).replace(/'/g, "''")}'`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const cols = (...names) => names.join(', ');
const vals = (...vs) => vs.map(q).join(', ');

// tabel, kolom, urutan — harus sama dengan src/lib/db/schema.ts
const TABLES = [
  {
    name: 'coffee_users',
    columns: ['id', 'email', 'name', 'password_hash', 'role', 'created_at', 'updated_at'],
    map: (r) => vals(r.id, r.email, r.name, r.password_hash, r.role, r.created_at, r.updated_at),
  },
  {
    name: 'coffee_menu_items',
    columns: ['id', 'slug', 'section', 'title_en', 'title_id', 'desc_en', 'desc_id', 'price', 'img', 'position', 'is_published', 'created_at', 'updated_at'],
    map: (r) => vals(r.id, r.slug, r.section, r.title_en, r.title_id, r.desc_en, r.desc_id, r.price, r.img, r.position, r.is_published, r.created_at, r.updated_at),
  },
  {
    name: 'coffee_chefs',
    columns: ['id', 'slug', 'name', 'role_en', 'role_id', 'img', 'bio_en', 'bio_id', 'position', 'is_published', 'created_at', 'updated_at'],
    map: (r) => vals(r.id, r.slug, r.name, r.role_en, r.role_id, r.img, r.bio_en, r.bio_id, r.position, r.is_published, r.created_at, r.updated_at),
  },
  {
    name: 'coffee_blog_posts',
    columns: ['id', 'slug', 'title_en', 'title_id', 'title_cn', 'excerpt_en', 'excerpt_id', 'excerpt_cn', 'content_en', 'content_id', 'content_cn', 'image', 'author_name', 'published_at', 'is_published', 'created_at', 'updated_at'],
    map: (r) => vals(r.id, r.slug, r.title_en, r.title_id, r.title_cn, r.excerpt_en, r.excerpt_id, r.excerpt_cn, r.content_en, r.content_id, r.content_cn, r.image, r.author_name, r.published_at, r.is_published, r.created_at, r.updated_at),
  },
  {
    name: 'coffee_settings',
    columns: ['id', 'default_language', 'active_languages', 'google_maps_iframe', 'opening_time', 'updated_at'],
    map: (r) => vals(r.id, r.default_language, r.active_languages, r.google_maps_iframe, r.opening_time, r.updated_at),
  },
];

async function main() {
  const sqlClient = postgres(url, { max: 1 });
  const out = [
    '-- Generated by scripts/export-postgres-to-d1.js',
    '-- Import dengan: npx wrangler d1 execute DB --file db/export/d1-import.sql --remote',
    'PRAGMA foreign_keys=OFF;',
    '',
  ];

  try {
    for (const t of TABLES) {
      const rows = await sqlClient`SELECT * FROM ${sqlClient(t.name)}`;
      console.log(`📦 ${t.name}: ${rows.length} baris`);
      for (const r of rows) {
        out.push(
          `INSERT OR IGNORE INTO ${t.name} (${cols(...t.columns)}) VALUES (${t.map(r)});`,
        );
      }
      out.push('');
    }
  } finally {
    await sqlClient.end();
  }

  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, out.join('\n'), 'utf8');
  console.log(`\n✅ Export selesai → ${outFile}`);
  console.log('▶ Import ke D1: npx wrangler d1 execute DB --file db/export/d1-import.sql --remote');
}

main().catch((err) => {
  console.error('❌ Export gagal:', err);
  process.exit(1);
});
